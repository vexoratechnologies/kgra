/// AppSpacing defines vertical and horizontal spacing tokens based on a 4px baseline grid.
/// 
/// Consistent spacing aligns the visual hierarchy to the Clinical Integrity specifications.
class AppSpacing {
  AppSpacing._();

  /// 4.0 px base spacing
  static const double base = 4.0;

  /// Extra small spacing (4.0 px)
  static const double xs = 4.0;

  /// Small spacing (8.0 px) - e.g., spacing between headline and related body text
  static const double sm = 8.0;

  /// Medium spacing (16.0 px) - e.g., list items, default grid gutters
  static const double md = 16.0;

  /// Large spacing (24.0 px) - e.g., spacing between screen sections
  static const double lg = 24.0;

  /// Extra large spacing (32.0 px) - e.g., screen margins
  static const double xl = 32.0;

  /// Double extra large spacing (48.0 px)
  static const double xxl = 48.0;

  /// Triple extra large spacing (64.0 px)
  static const double xxxl = 64.0;
}
